def get_nutrition(label: str, portion_grams: float = None):
    key = label.lower().replace(" ", "_")
    kcal_100, p_100, c_100, f_100, default_g = NUTRITION_DATA.get(
        key, (200, 8.0, 25.0, 8.0, 200)
    )
    grams = float(portion_grams) if portion_grams else float(default_g)
    factor = grams / 100.0
    return {
        "food_key": key,
        "display_name": key.replace("_", " ").title(),
        "portion_grams": round(grams, 1),
        "default_serving": default_g,
        "calories": round(kcal_100 * factor, 1),
        "protein": round(p_100 * factor, 1),
        "carbs": round(c_100 * factor, 1),
        "fat": round(f_100 * factor, 1),
        "per_100g": {
            "calories": kcal_100,
            "protein": p_100,
            "carbs": c_100,
            "fat": f_100,
        },
    }


